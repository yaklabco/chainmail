// Read limits.
const (
	defaultReadLimit = 100
	maxReadLimit     = 1000
	// readChunk is how many rows Read fetches per query. Rows are collected
	// and closed before any are decoded, as the single connection requires.
	readChunk = 500
	// maxScan caps the rows one Read examines, so a filter that matches
	// nothing cannot walk the whole log in one call. Read then returns fewer
	// events with Next advanced, and the caller reads again from Next.
	maxScan = 5000
)

// queryer is what *sql.DB and *sql.Tx share for reads.
type queryer interface {
	QueryContext(ctx context.Context, query string, args ...any) (*sql.Rows, error)
	QueryRowContext(ctx context.Context, query string, args ...any) *sql.Row
}

// Query reads events after a position.
type Query struct {
	After  int64
	Filter Filter
	Limit  int // 1 to 1000; 0 means 100
}

// Page is one read.
type Page struct {
	// Events matched the filter, ascending by ID. A trimmed gap, when the
	// start fell below the oldest retained event, comes first.
	Events []Event
	// Next is the highest ID this read examined, matched or not, or After
	// when it examined none. Reading from Next continues without skipping.
	// A read examines at most 5000 rows, so a page can be empty while Next
	// moves forward: a reader is caught up only when Next == After. When a
	// trimmed gap is generated, Next is at least the gap's NextID - 1.
	Next int64
}

// GroupInfo describes a named group.
type GroupInfo struct {
	Name       string
	AckedID    int64
	Lag        int64 // events with ID above AckedID
	CreatedAt  time.Time
	LastSeenAt time.Time
}

// Log is the event log in state.db. It is safe for concurrent use. Wait
// only wakes on Notify calls made on the same *Log, so the daemon builds
// exactly one and shares it.
type Log struct {
	db  *sql.DB
	now func() time.Time
	// logger receives failures of the trims in Run. Records never hold
	// event content.
	logger *slog.Logger

	// trimBatch is the most events one Trim transaction deletes: 0 means
	// defaultTrimBatch. afterTrimBatch, when set, runs after each batch
	// commits. Tests set both.
	trimBatch      int
	afterTrimBatch func()

	// mu guards notify, which Notify closes and replaces so that every
	// Wait blocked on the old channel wakes at once.
	mu     sync.Mutex
	notify chan struct{}
}

// NewLog returns a Log over db, which must hold the state schema. now
// supplies event and group times, and logger receives the failed trims of
// Run. A nil now uses time.Now, and a nil logger discards.
func NewLog(db *sql.DB, now func() time.Time, logger *slog.Logger) *Log {
	if now == nil {
		now = time.Now
	}
	if logger == nil {
		logger = slog.New(slog.DiscardHandler)
	}
	return &Log{db: db, now: now, logger: logger, notify: make(chan struct{})}
}

// Append inserts events in tx and sets their IDs. The caller commits, then
// calls Notify. An event with a zero At is stamped with the log's clock.
// Trimmed gaps are generated by Read and never stored, so Append refuses
// them. tx holds the only connection, so nothing may call another Log or
// State method between Append and the commit: it would wait for that
// connection forever.
func (l *Log) Append(ctx context.Context, tx *sql.Tx, events []Event) error {
	if len(events) == 0 {
		return nil
	}
	stmt, err := tx.PrepareContext(ctx,
		"INSERT INTO events (at, account, folder, kind, ref, payload) VALUES (?, ?, ?, ?, ?, ?)")
	if err != nil {
		return fmt.Errorf("preparing event insert: %w", err)
	}
	defer func() { _ = stmt.Close() }() // closing a prepared statement only frees it
	for i := range events {
		e := &events[i]
		if e.Kind == KindGap && e.Reason == GapTrimmed {
			return errors.New("trimmed gaps are generated at read time and never stored")
		}
		payload, err := encodePayload(*e)
		if err != nil {
			return err
		}
		if e.At.IsZero() {
			e.At = l.now().UTC()
		}
		res, err := stmt.ExecContext(ctx, formatTime(e.At), e.Account, e.Folder, string(e.Kind), e.Ref, payload)
		if err != nil {
			return fmt.Errorf("appending %s event: %w", e.Kind, err)
		}
		if e.ID, err = res.LastInsertId(); err != nil {
			return fmt.Errorf("appending %s event: %w", e.Kind, err)
		}
	}
	return nil
}

// Notify wakes every Wait.
func (l *Log) Notify() {
	l.mu.Lock()
	defer l.mu.Unlock()
	close(l.notify)
	l.notify = make(chan struct{})
}

// Publish appends events in its own transaction, commits, and notifies.
func (l *Log) Publish(ctx context.Context, events ...Event) error {
	if len(events) == 0 {
		return nil
	}
	tx, err := l.db.BeginTx(ctx, nil)
	if err != nil {
		return fmt.Errorf("beginning publish: %w", err)
	}
	defer func() { _ = tx.Rollback() }() // a no-op after Commit; an earlier error is the one to report
	if err := l.Append(ctx, tx, events); err != nil {
		return err
	}
	if err := tx.Commit(); err != nil {
		return fmt.Errorf("committing publish: %w", err)
	}
	l.Notify()
	return nil
}

// Read returns events after q.After. It never blocks.
//
// When q.After is below Tail and the lowest retained ID is above
// q.After+1, or nothing is retained, the page starts with a trimmed gap
// (ID 0, At now, NextID the lowest retained ID, or Tail+1 when none) and
// continues from the lowest retained ID. The gap passes through q.Filter
// like any event and counts toward the limit. Next then counts every ID
// below NextID as examined. Read examines at most 5000 rows, so a page can
// hold fewer than Limit events, even none, with Next above q.After; the
// caller reads again from Next.
func (l *Log) Read(ctx context.Context, q Query) (Page, error) {
	limit := q.Limit
	if limit == 0 {
		limit = defaultReadLimit
	}
	if limit < 1 || limit > maxReadLimit {
		return Page{}, fmt.Errorf("read limit %d must be 1 to %d", q.Limit, maxReadLimit)
	}
	if q.After < 0 {
		// A negative start would look like a read from below the oldest
		// event and produce a trimmed gap that hides nothing.
		return Page{}, fmt.Errorf("read position %d must not be negative", q.After)
	}
	// One read transaction gives a consistent view, so a Trim cannot remove
	// events between the gap check and the scan.
	tx, err := l.db.BeginTx(ctx, nil)
	if err != nil {
		return Page{}, fmt.Errorf("beginning read: %w", err)
	}
	defer func() { _ = tx.Rollback() }() // read-only; nothing to keep

	page := Page{Next: q.After}
	after := q.After
	tail, err := tailOf(ctx, tx)
	if err != nil {
		return Page{}, err
	}
	if after < tail {
		var oldest int64
		if err := tx.QueryRowContext(ctx, "SELECT COALESCE(MIN(id), 0) FROM events").Scan(&oldest); err != nil {
			return Page{}, fmt.Errorf("reading the oldest event: %w", err)
		}
		if oldest == 0 || oldest > after+1 {
			next := oldest
			if oldest == 0 {
				next = tail + 1
			}
			gap := Event{At: l.now().UTC(), Kind: KindGap, Reason: GapTrimmed, NextID: next}
			if q.Filter.Match(gap) {
				page.Events = append(page.Events, gap)
			}
			after = next - 1
			page.Next = after
		}
	}

	for examined := 0; examined < maxScan && len(page.Events) < limit; {
		chunk, err := readRows(ctx, tx, after, readChunk)
		if err != nil {
			return Page{}, err
		}
		for _, r := range chunk {
			e, err := r.event()
			if err != nil {
				return Page{}, err
			}
			after, page.Next = e.ID, e.ID
			examined++
			if q.Filter.Match(e) {
				page.Events = append(page.Events, e)
			}
			if len(page.Events) == limit || examined == maxScan {
				break
			}
		}
		if len(chunk) < readChunk {
			break
		}
	}
	return page, nil
}

// eventRow is one events row as stored, before decoding.
type eventRow struct {
	id                                   int64
	at, account, folder, kind, ref, body string
}

// readRows returns up to n rows with ID above after, ascending. It closes
// its Rows before returning.
func readRows(ctx context.Context, q queryer, after int64, n int) ([]eventRow, error) {
	rows, err := q.QueryContext(ctx,
		"SELECT id, at, account, folder, kind, ref, payload FROM events WHERE id > ? ORDER BY id LIMIT ?",
		after, n)
	if err != nil {
		return nil, fmt.Errorf("reading events: %w", err)
	}
	defer func() { _ = rows.Close() }() // read-only; rows.Err reports any read failure
	var out []eventRow
	for rows.Next() {
		var r eventRow
		if err := rows.Scan(&r.id, &r.at, &r.account, &r.folder, &r.kind, &r.ref, &r.body); err != nil {
			return nil, fmt.Errorf("reading events: %w", err)
		}
		out = append(out, r)
	}
	if err := rows.Err(); err != nil {
		return nil, fmt.Errorf("reading events: %w", err)
	}
	return out, nil
}

// event decodes the row.
func (r eventRow) event() (Event, error) {
	at, err := parseTime(r.at)
	if err != nil {
		return Event{}, fmt.Errorf("event %d: %w", r.id, err)
	}
	e := Event{ID: r.id, At: at, Kind: Kind(r.kind), Account: r.account, Folder: r.folder, Ref: r.ref}
	if err := decodePayload(&e, r.body); err != nil {
		return Event{}, err
	}
	return e, nil
}

// Tail is the highest ID ever assigned (sqlite_sequence), 0 when none.
func (l *Log) Tail(ctx context.Context) (int64, error) {
	return tailOf(ctx, l.db)
}

func tailOf(ctx context.Context, q queryer) (int64, error) {
	var tail int64
	err := q.QueryRowContext(ctx,
		"SELECT COALESCE((SELECT seq FROM sqlite_sequence WHERE name = 'events'), 0)").Scan(&tail)
	if err != nil {
		return 0, fmt.Errorf("reading the log tail: %w", err)
	}
	return tail, nil
}

// Trim deletes events older than retention, then the oldest beyond
// maxEvents, then client groups not seen for longer than retention. Cache
// groups (IsCacheGroup) never expire: the daemon owns them and recreates
// none of their state, so a long pause of the cache must not reset it. It
// returns the number of events deleted. Both event trims remove only a
// prefix of IDs, oldest first, so the trimmed gap in Read reports every
// loss: an event older than retention that follows a retained one (a
// caller-supplied At, or a clock that stepped back) stays until those
// before it go.
//
// Each trim finds its bound first, then deletes below it in batches of at
// most 5000 events, each its own transaction, so a large trim never holds
// the only connection for long and readers and writers get turns between
// batches. A batch is a prefix too, so a trim cut short by an error or by
// ctx leaves the log trimmed from its oldest end, and the count returned
// with the error is what it deleted.
func (l *Log) Trim(ctx context.Context, retention time.Duration, maxEvents int) (int64, error) {
	if retention <= 0 || maxEvents < 1 {
		return 0, fmt.Errorf("trim needs a positive retention and max events, got %s and %d", retention, maxEvents)
	}
	cutoff := formatTime(l.now().Add(-retention))
	var deleted int64
	for _, bound := range []struct {
		query string
		args  []any
	}{
		// The oldest ID still inside retention, or one past the newest when
		// none is: everything below it goes. NULL on an empty log.
		{`SELECT COALESCE((SELECT MIN(id) FROM events WHERE at >= ?), (SELECT MAX(id) + 1 FROM events))`, []any{cutoff}},
		// One past the newest ID beyond the cap, NULL when there are not
		// that many events.
		{"SELECT (SELECT id FROM events ORDER BY id DESC LIMIT 1 OFFSET ?) + 1", []any{maxEvents}},
	} {
		var below sql.NullInt64
		if err := l.db.QueryRowContext(ctx, bound.query, bound.args...).Scan(&below); err != nil {
			return deleted, fmt.Errorf("trimming events: %w", err)
		}
		if !below.Valid {
			continue
		}
		n, err := l.deleteBelow(ctx, below.Int64)
		deleted += n
		if err != nil {
			return deleted, err
		}
	}
	if _, err := l.db.ExecContext(ctx,
		"DELETE FROM event_groups WHERE last_seen_at < ? AND name NOT LIKE 'cache.%'", cutoff); err != nil {
		return deleted, fmt.Errorf("pruning groups: %w", err)
	}
	return deleted, nil
}

// defaultTrimBatch is the most events one Trim transaction deletes.
const defaultTrimBatch = 5000

// deleteBelow deletes every event with an ID below id, lowest first, in
// batches of trimBatch, each a transaction of its own, and returns how many
// it deleted.
func (l *Log) deleteBelow(ctx context.Context, id int64) (int64, error) {
	batch := cmp.Or(l.trimBatch, defaultTrimBatch)
	var deleted int64
	for {
		res, err := l.db.ExecContext(ctx,
			"DELETE FROM events WHERE id IN (SELECT id FROM events WHERE id < ? ORDER BY id LIMIT ?)", id, batch)
		if err != nil {
			return deleted, fmt.Errorf("trimming events: %w", err)
		}
		n, err := res.RowsAffected()
		if err != nil {
			return deleted, fmt.Errorf("trimming events: %w", err)
		}
		deleted += n
		if n == 0 {
			return deleted, nil
		}
		if l.afterTrimBatch != nil {
			l.afterTrimBatch()
		}
		if n < int64(batch) {
			return deleted, nil
		}
	}
}

// Run trims every interval until ctx ends. It trims once on entry too, so a
// daemon that restarts often still trims. A failed trim is logged to the
// Log's logger and retried at the next tick; one cut short because ctx
// ended is not logged. A non-positive interval means an hour.
func (l *Log) Run(ctx context.Context, interval, retention time.Duration, maxEvents int) {
	if interval <= 0 {
		interval = time.Hour
	}
	ticker := time.NewTicker(interval)
	defer ticker.Stop()
	for {
		if _, err := l.Trim(ctx, retention, maxEvents); err != nil && ctx.Err() == nil {
			l.logger.ErrorContext(ctx, "trimming the event log failed", "err", err)
		}
		select {
		case <-ctx.Done():
			return
		case <-ticker.C:
		}
	}
}

// changed returns the channel the next Notify closes.
func (l *Log) changed() <-chan struct{} {
	l.mu.Lock()
	defer l.mu.Unlock()
	return l.notify
}

// Wait blocks until an event with ID above after exists or ctx ends.
func (l *Log) Wait(ctx context.Context, after int64) error {
	for {
		// Take the channel before reading Tail, so a Notify that lands
		// between the two still wakes the select below.
		woken := l.changed()
		tail, err := l.Tail(ctx)
		if err != nil {
			return err
		}
		if tail > after {
			return nil
		}
		select {
		case <-ctx.Done():
			return fmt.Errorf("waiting for events: %w", ctx.Err())
		case <-woken:
		}
	}
}

// Group returns the group's acknowledged ID, creating the group at Tail
// when it does not exist, and stamps last_seen_at.
func (l *Log) Group(ctx context.Context, name string) (acked int64, created bool, err error) {
	if !logGroupName(name) {
		return 0, false, fmt.Errorf("invalid group name %q", name)
	}
	tx, err := l.db.BeginTx(ctx, nil)
	if err != nil {
		return 0, false, fmt.Errorf("beginning group %s: %w", name, err)
	}
	defer func() { _ = tx.Rollback() }() // a no-op after Commit; an earlier error is the one to report

	now := formatTime(l.now())
	err = tx.QueryRowContext(ctx, "SELECT acked_id FROM event_groups WHERE name = ?", name).Scan(&acked)
	switch {
	case errors.Is(err, sql.ErrNoRows):
		if acked, err = tailOf(ctx, tx); err != nil {
			return 0, false, err
		}
		created = true
		_, err = tx.ExecContext(ctx,
			"INSERT INTO event_groups (name, acked_id, created_at, last_seen_at) VALUES (?, ?, ?, ?)",
			name, acked, now, now)
	case err == nil:
		_, err = tx.ExecContext(ctx, "UPDATE event_groups SET last_seen_at = ? WHERE name = ?", now, name)
	}
	if err != nil {
		return 0, false, fmt.Errorf("group %s: %w", name, err)
	}
	if err := tx.Commit(); err != nil {
		return 0, false, fmt.Errorf("committing group %s: %w", name, err)
	}
	return acked, created, nil
}

// TouchGroup stamps the group's last_seen_at, in one UPDATE, and changes
// nothing else. A stream that holds a group open calls it at every
// heartbeat, so Trim never prunes a group that is in use but quiet. An
// unknown group is not created: one deleted while its stream runs stays
// deleted.
func (l *Log) TouchGroup(ctx context.Context, name string) error {
	if !logGroupName(name) {
		return fmt.Errorf("invalid group name %q", name)
	}
	if _, err := l.db.ExecContext(ctx, "UPDATE event_groups SET last_seen_at = ? WHERE name = ?", formatTime(l.now()), name); err != nil {
		return fmt.Errorf("touching group %s: %w", name, err)
	}
	return nil
}

// Ack raises the group's acknowledged ID to id. It never lowers it, and
// never raises it above Tail. An unknown group is created. Ack stamps
// last_seen_at.
func (l *Log) Ack(ctx context.Context, name string, id int64) error {
	if !logGroupName(name) {
		return fmt.Errorf("invalid group name %q", name)
	}
	tx, err := l.db.BeginTx(ctx, nil)
	if err != nil {
		return fmt.Errorf("beginning ack for %s: %w", name, err)
	}
	defer func() { _ = tx.Rollback() }() // a no-op after Commit; an earlier error is the one to report

	tail, err := tailOf(ctx, tx)
	if err != nil {
		return err
	}
	id = max(0, min(id, tail))
	now := formatTime(l.now())
	_, err = tx.ExecContext(ctx,
		`INSERT INTO event_groups (name, acked_id, created_at, last_seen_at) VALUES (?, ?, ?, ?)
		 ON CONFLICT (name) DO UPDATE SET acked_id = max(acked_id, excluded.acked_id), last_seen_at = excluded.last_seen_at`,
		name, id, now, now)
	if err != nil {
		return fmt.Errorf("acknowledging %s: %w", name, err)
	}
	if err := tx.Commit(); err != nil {
		return fmt.Errorf("committing ack for %s: %w", name, err)
	}
	return nil
}

// ResetGroup moves the group's acknowledged ID from exactly from to to,
// and stamps last_seen_at, in one compare-and-set statement. It reports
// whether it applied: it does not when the group no longer stands at from,
// because another reader recovered or acknowledged it first, or when the
// group does not exist. It is the recovery for a group left acknowledged
// past the tail, as a reset of the state database leaves one: such a group
// belongs to a log that no longer exists. It is not an acknowledgement, so
// unlike Ack it can lower the ID, and it does not cap to at Tail.
func (l *Log) ResetGroup(ctx context.Context, name string, from, to int64) (bool, error) {
	if !logGroupName(name) {
		return false, fmt.Errorf("invalid group name %q", name)
	}
	if to < 0 {
		return false, fmt.Errorf("group %s reset to negative ID %d", name, to)
	}
	res, err := l.db.ExecContext(ctx,
		"UPDATE event_groups SET acked_id = ?, last_seen_at = ? WHERE name = ? AND acked_id = ?",
		to, formatTime(l.now()), name, from)
	if err != nil {
		return false, fmt.Errorf("resetting group %s: %w", name, err)
	}
	n, err := res.RowsAffected()
	if err != nil {
		return false, fmt.Errorf("resetting group %s: %w", name, err)
	}
	return n > 0, nil
}

// Groups lists every group by name, with its lag in retained events.
func (l *Log) Groups(ctx context.Context) ([]GroupInfo, error) {
	rows, err := l.db.QueryContext(ctx,
		`SELECT g.name, g.acked_id, g.created_at, g.last_seen_at,
		        (SELECT count(*) FROM events e WHERE e.id > g.acked_id)
		 FROM event_groups g ORDER BY g.name`)
	if err != nil {
		return nil, fmt.Errorf("listing groups: %w", err)
	}
	defer func() { _ = rows.Close() }() // read-only; rows.Err reports any read failure
	type row struct {
		info              GroupInfo
		created, lastSeen string
	}
	var raw []row
	for rows.Next() {
		var r row
		if err := rows.Scan(&r.info.Name, &r.info.AckedID, &r.created, &r.lastSeen, &r.info.Lag); err != nil {
			return nil, fmt.Errorf("listing groups: %w", err)
		}
		raw = append(raw, r)
	}
	if err := rows.Err(); err != nil {
		return nil, fmt.Errorf("listing groups: %w", err)
	}
	out := make([]GroupInfo, 0, len(raw))
	for _, r := range raw {
		if r.info.CreatedAt, err = parseTime(r.created); err != nil {
			return nil, fmt.Errorf("group %s: %w", r.info.Name, err)
		}
		if r.info.LastSeenAt, err = parseTime(r.lastSeen); err != nil {
			return nil, fmt.Errorf("group %s: %w", r.info.Name, err)
		}
		out = append(out, r.info)
	}
	return out, nil
}

// DeleteGroup reports whether the group existed.
func (l *Log) DeleteGroup(ctx context.Context, name string) (bool, error) {
	res, err := l.db.ExecContext(ctx, "DELETE FROM event_groups WHERE name = ?", name)
	if err != nil {
		return false, fmt.Errorf("deleting group %s: %w", name, err)
	}
	n, err := res.RowsAffected()
	if err != nil {
		return false, fmt.Errorf("deleting group %s: %w", name, err)
	}
	return n > 0, nil
}

// maxGroupName is the longest group name ValidGroupName accepts.
const maxGroupName = 64

// ValidGroupName reports whether name is a valid client group name:
// ^[a-z0-9][a-z0-9._-]{0,63}$, not starting with "cache.", which is
// reserved for the daemon's cache groups (IsCacheGroup).
func ValidGroupName(name string) bool {
	if name == "" || len(name) > maxGroupName || strings.HasPrefix(name, cacheGroupPrefix) {
		return false
	}
	for i := range len(name) {
		c := name[i]
		switch {
		case 'a' <= c && c <= 'z', '0' <= c && c <= '9':
		case i > 0 && (c == '.' || c == '_' || c == '-'):
		default:
			return false
		}
	}
	return true
}
